export function findRulesJournal() {
  return game.journal?.find(j => j.flags?.[SYSTEM_ID]?.arcanaRules)
      ?? game.journal?.getName(RULES_TITLE)
      ?? null;
}

export async function buildRulesJournal({ notify = true } = {}) {
  const pages = rulesPages().map((p, i) => ({
    name: p.name, type: "text",
    title: { show: true, level: 1 },
    text: { format: 1, content: p.html },
    sort: (i + 1) * 100,
    ownership: { default: -1 }
  }));

  let journal = findRulesJournal();
  if (journal) {
    // Update in place, by page name, so page ids — and any links to them —
    // survive. Only pages whose text actually changed are written.
    const byName = new Map(journal.pages.map(p => [p.name, p]));
    const updates = [], creates = [];
    for (const page of pages) {
      const hit = byName.get(page.name);
      if (!hit) creates.push(page);
      else if (hit.text?.content !== page.text.content || hit.sort !== page.sort) updates.push({ _id: hit.id, "text.content": page.text.content, sort: page.sort });
      byName.delete(page.name);
    }
    const stale = [...byName.values()].map(p => p.id);
    if (updates.length) await journal.updateEmbeddedDocuments("JournalEntryPage", updates);
    if (creates.length) await journal.createEmbeddedDocuments("JournalEntryPage", creates);
    if (stale.length) await journal.deleteEmbeddedDocuments("JournalEntryPage", stale);
    if (notify) ui.notifications.info(`${RULES_TITLE}: ${updates.length + creates.length ? "rules refreshed" : "already up to date"}.`);
    return journal;
  }

  const folder = game.folders.find(f => f.name === FOLDER && f.type === "JournalEntry")
              ?? await Folder.create({ name: FOLDER, type: "JournalEntry", color: "#4a3c8c" });

  journal = await JournalEntry.create({
    name: RULES_TITLE, folder: folder.id, pages,
    ownership: { default: CONST.DOCUMENT_OWNERSHIP_LEVELS.OBSERVER },
    flags: { [SYSTEM_ID]: { arcanaRules: true } }
  });
  if (notify) ui.notifications.info(`${RULES_TITLE}: created with ${pages.length} sections.`);
  return journal;
}

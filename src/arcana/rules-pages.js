/* ===================================================================
 * Dreoarcana Arcana — the rules pages
 *
 * The rules, readable inside Foundry. Every table is rendered from
 * rules.js when it is shown, so the pages can never disagree with what
 * the builder does. The Arcanum's Rules tab shows them directly; the GM
 * can also publish them as a journal. Pages 1–8 are the Spell Builder
 * and Node Catalogue; pages 9–10 are the house procedure on the table.
 * =================================================================== */

import { SYSTEM_ID } from "./core.js";
import { INTENTS, CONVERSIONS, FORMS, RANGES, SIZES, EFFECTS, DISCIPLINES, UTILITY_NODES,
         DAMAGE_TYPES, TIERS, TIER_DIFFICULTY, DIFFICULTY_GRADES, OUTCOMES, FOCUS_PRESETS,
         CATALYST_PRESETS, COMPOUND_COMPLEXITY_BONUS, CIRCUMSTANCES } from "./rules.js";
import { setting, SETTINGS } from "./settings.js";
import { e } from "./html.js";

export const RULES_TITLE = "Arcana — Spell Builder";
const FOLDER = "Dreoarcana";

const table = (head, rows) =>
  `<table><thead><tr>${head.map(h => `<th>${h}</th>`).join("")}</tr></thead><tbody>${
    rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table>`;

function pageFormulas() {
  return `
    <p>There are five important formulas for the spell casting.</p>
    ${table(["Formula", "Equation"], [
      ["Heat Formula", "H = Œ<sup>1.3</sup> × Complexity ÷ 6"],
      ["First Principle", "Œ = ξ × 1 ÷ (F × S)"],
      ["Second Principle", "Œ = ξ × 1 ÷ (F × S) × C"],
      ["Casting Time", "T<sub>cast</sub> = 4 s + Σ(C<sub>mods</sub>) × Γ"],
      ["Might Formula", "M = ξ"]
    ])}
    <h3>Variables</h3>
    ${table(["Symbol", "Name", "Description"], [
      ["ξ", "Converted Energy", "Energy the spell produces based on node selection (damage, healing, utility). Determined by the node ξ multipliers on the Power invested."],
      ["Complexity", "Spell Complexity", "Sum of all node complexity values. Used for Heat and Casting Time."],
      ["F", "Focus", "Reflects caster's mental strain or divided attention."],
      ["S", "Skill", "Caster's mastery over ξ flow. Higher S → more efficient conversion."],
      ["Œ", "Orie (raw energy)", "Calculated from ξ using intrinsic caster factors. Core Principle output before catalysts."],
      ["Γ", "Catalyst Quality", "Efficiency of external tools/conduits. Multiplies Œ_base; optional post-conversion modifier."],
      ["Œ_final", "Orie (final)", "Raw energy required after applying catalyst. Feeds Heat, Casting Time and dice."],
      ["H", "Heat", "Magical strain generated by spell. Depends on Œ_final and Complexity."],
      ["T_cast", "Casting Time", "Base 4 s + complexity modifiers."],
      ["Stored Orie", "—", "Reduces required Œ to produce the same ξ. Automatically reduces Heat."]
    ])}
    <h3>How the table reads them</h3>
    <ul>
      <li><strong>Power (N)</strong> is the ξ the caster puts in; every node multiplies it. ξ = N × Π(node ξ).</li>
      <li><strong>Skill S</strong> comes from the Mythras percentage: S = skill% ÷ ${setting(SETTINGS.skillDivisor) ?? 50}.</li>
      <li><strong>Focus F</strong> is an efficiency between 0 and 1 — full attention is 1, distraction lowers it and so raises Œ. The source says F &gt; 1 "reduces efficiency" while dividing by it; this keeps the formula literal and the intent intact.</li>
      <li><strong>Catalyst Γ</strong> multiplies Œ (Second Principle) and the complexity term of casting time. 1.0 is bare hands; a better catalyst is lower.</li>
      <li><strong>Stored Orie</strong> drawn for a cast is subtracted from Œ_final before conversion. Only what is converted heats: H uses Œ_final − drawn.</li>
      <li><strong>Might</strong> is shared evenly between a spell's effects for their magnitude; cost and Heat are paid on the whole.</li>
    </ul>`;
}

function pageIntents() {
  return `<p>Intent is priced by kindness: helping is cheaper than harming, and making something from nothing is the most expensive thing you can do.</p>
    ${table(["Name", "Short description", "ξ drain", "Complexity"],
      Object.entries(INTENTS).map(([k, v]) => [k, e(v.desc), `×${v.xi.toFixed(2)}`, v.complexity]))}`;
}

function pageConversions() {
  return `<p>Conversion nodes are where the risk lives. One node choice, and the caster has decided whether to be careful or quick.</p>
    ${table(["Name", "Description", "Œ modifier", "Complexity factor", "Tier"],
      Object.entries(CONVERSIONS).map(([k, v]) => [k, e(v.desc), `×${v.orie}`, `×${v.complexityFactor}`, "I"]))}`;
}

function pageShapes() {
  const forms = TIERS.map(t => {
    const rows = Object.entries(FORMS).filter(([, f]) => f.tier === t.tier)
      .map(([k, f]) => [`<strong>${k}</strong>`, e(f.desc), f.complexity, `×${f.xi.toFixed(2)}`, e(f.notes)]);
    return rows.length ? `<h4>Tier ${t.numeral} Forms</h4>${table(["Shape", "Description", "Complexity", "ξ ×", "Notes"], rows)}` : "";
  }).join("");
  return `${forms}
    <h3>Range</h3>
    ${table(["Tier", "Descriptor", "Effective distance", "ξ range mod", "Description"],
      Object.entries(RANGES).map(([k, r]) => [TIERS[k - 1].numeral, r.label, `${r.distance} (${r.metres})`, `×${r.xi.toFixed(2)}`, e(r.desc)]))}
    <h3>Size</h3>
    ${table(["Tier", "Descriptor", "Area / volume", "ξ multiplier", "Description"],
      Object.entries(SIZES).map(([k, s]) => [TIERS[k - 1].numeral, s.label, `${s.area} (${s.metres})`, `×${s.xi.toFixed(2)}`, e(s.desc)]))}
    <p><strong>Shape Total Mod = ξ<sub>range</sub> × ξ<sub>shape</sub> × ξ<sub>size</sub></strong></p>`;
}

